"""Outdoor comfort (Micro Clima), verification step 2: the engine's values (verify_dump.js) against reference
implementations and exact solutions. Writes verification.md.
- Sun position: pvlib, NREL solar position algorithm (Reda and Andreas 2004), at the middle of each hour.
- Sun on walls: pvlib Perez 1990 transposition with the engine's sun position, albedo 0.2.
- UTCI: pythermalcomfort utci (operational polynomial, Broede et al. 2012), 3,000 random conditions.
- SolarCal, direct sun on the body: pythermalcomfort solar_gain with no diffuse light, averaged over the sun's direction
  relative to the body (0 to 180° in 15° steps, as the engine), standing and seated.
- Ground conduction: periodic air temperature over a semi-infinite solid with a convective surface, exact solution
  T_s / T_a = h / (h + e sqrt(i w)), e = sqrt(k rho c).
- Time step: 2 against 12 sub-steps per hour."""
import json, os, sys, numpy as np, pandas as pd, pvlib
from pythermalcomfort.models import utci as ptc_utci, solar_gain
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from paths import WORK
HERE = os.path.dirname(os.path.abspath(__file__)); R = json.load(open(os.path.join(WORK, "outdoor", "verify.json")))
md = ["# Micro Clima: code verification", "", "Each part of the engine against a reference implementation or an exact solution. Generated by `verify.py`.", ""]
# sun
md += ["## Sun position and sun on walls (pvlib)", "", "| Climate | Elevation, bias / largest | Azimuth above 5°, RMS / largest | Walls N / E / S / W, annual difference | Hourly RMS, largest wall |", "|---|---|---|---|---|"]
for name, d in R["sun"].items():
    tz = d["tz"]; times = pd.date_range("2023-01-01 00:30", periods=8760, freq="h", tz=f"Etc/GMT{-int(tz):+d}")
    sp = pvlib.solarposition.get_solarposition(times, d["lat"], d["lon"], method="nrel_numpy")
    el, az = np.array(d["el"]), np.array(d["az"]); rel, raz = 90 - sp["apparent_zenith"].to_numpy(), sp["azimuth"].to_numpy()
    m = (rel > 0) | (el > 0); m2 = rel > 5; de = el[m] - rel[m]; da = ((az[m2] - raz[m2] + 540) % 360) - 180
    dni = np.where(el > 0, np.array(d["dni"]), 0.0); dhi = np.array(d["dhi"]); ghi = np.array(d["ghi"])
    extra = pvlib.irradiance.get_extra_radiation(times).to_numpy(); am = pvlib.atmosphere.get_relative_airmass(90 - el)
    dif, rms = [], []
    for f, arr in d["wall"].items():
        ref = np.nan_to_num(np.asarray(pvlib.irradiance.get_total_irradiance(90, float(f), 90 - el, az, dni, ghi, dhi, dni_extra=extra, airmass=am, albedo=0.2, model="perez")["poa_global"], dtype=float))
        mine = np.array(arr); dif.append(100 * (mine.sum() / ref.sum() - 1)); rms.append(np.sqrt(np.mean((mine - ref) ** 2)))
    md.append(f"| {name} | {de.mean():+.2f}° / {np.abs(de).max():.2f}° | {np.sqrt((da ** 2).mean()):.2f}° / {np.abs(da).max():.2f}° | {' / '.join(f'{x:+.2f}%' for x in dif)} | {max(rms):.1f} W/m² |")
# UTCI
U = np.array(R["utci"]); ref = ptc_utci(tdb=U[:, 0], tr=U[:, 1], v=U[:, 2], rh=U[:, 3], limit_inputs=False, round_output=False)
ref = np.asarray(ref.utci if hasattr(ref, "utci") else ref["utci"], dtype=float)
md += ["", "## UTCI (pythermalcomfort)", "", f"3,000 random conditions (air −45 to 50 °C, radiant minus air −25 to 70 K, wind 0.5 to 17 m/s, humidity 5 to 100 %): largest difference {np.nanmax(np.abs(U[:, 4] - ref)):.2e} K."]
# SolarCal
S = R["solar"]; rows = []
for el, dirn, seated, mine in S:
    post = "sitting" if seated else "standing"; sh = np.arange(0, 181, 15); w = np.array([0.5] + [1] * 11 + [0.5]) / 12
    r = solar_gain(sol_altitude=np.full(13, el), sharp=sh, sol_radiation_dir=np.full(13, dirn), sol_transmittance=np.ones(13), f_svv=np.zeros(13), f_bes=np.ones(13), asw=0.7, posture=post, floor_reflectance=0.0, round_output=False)
    dm = np.asarray(r.delta_mrt if hasattr(r, "delta_mrt") else r["delta_mrt"], dtype=float); rows.append(abs(mine - (w * dm).sum()))
md += ["", "## SolarCal, direct sun on the body (pythermalcomfort)", "", f"{len(S)} cases (sun elevation 5 to 90°, direct sun 100 to 800 W/m², standing and seated): largest difference {max(rows):.2e} K. The diffuse and reflected terms are the closed formula of SolarCal (0.5 f_eff of the diffuse and reflected light), written out in the engine. The difference comes from the radiation coefficient: the engine uses ASHRAE 55's 6.012 W/m²K (as Macro Clima and Ladybug), pythermalcomfort rounds it to 6, a 0.2 % difference."]
# conduction
md += ["", "## Ground conduction (exact solution)", "", "| Wave | Exact amplitude ratio / lag | Default grid, 2 steps per hour | Halved grid, 12 steps per hour |", "|---|---|---|---|"]
for lab, c in R["cond"].items():
    w = 2 * np.pi / c["P"]; e = np.sqrt(c["k"] * c["rc"]); r_ = e * np.sqrt(w / 3600); re, im = c["h"] + r_ / np.sqrt(2), r_ / np.sqrt(2)
    amp, lag = c["h"] / np.hypot(re, im), np.arctan2(im, re) / w
    def fit(ts, start):
        t = np.arange(1, 8761)[start:]; y = np.array(ts)[start:] - np.mean(ts[start:]); X = np.stack([np.sin(w * t), np.cos(w * t)], 1); a, b = np.linalg.lstsq(X, y, rcond=None)[0]
        return np.hypot(a, b) / 10, -np.arctan2(b, a) / w
    out = []
    for k in ("default", "fine"):
        A, L = fit(c[k], 7 * 24 if c["P"] == 24 else 0); out.append(f"{A:.4f} ({100 * (A / amp - 1):+.1f}%) / {L:.2f} h ({L - lag:+.2f} h)")
    md.append(f"| {lab} | {amp:.4f} / {lag:.2f} h | {out[0]} | {out[1]} |")
# time step
md += ["", "## Time step (2 against 12 sub-steps per hour)", "", "| Case | Ground surface, RMS / largest | UTCI, RMS |", "|---|---|---|"]
for k, d in R["step"].items():
    tg = (np.array(d["tg2"]) - np.array(d["tg12"])) / 10; u = (np.array(d["u2"]) - np.array(d["u12"])) / 10
    md.append(f"| {k} | {np.sqrt((tg ** 2).mean()):.2f} / {np.abs(tg).max():.2f} K | {np.sqrt((u ** 2).mean()):.3f} K |")
open(os.path.join(HERE, "verification.md"), "w").write("\n".join(md) + "\n"); print("\n".join(md))
